"""Hosting: copying a database (SQLite -> Postgres), and the Postgres adapter's small helpers.
Runs on SQLite by default; with SORT_SHERR_TEST_PG set, the copy target really is Postgres (see conftest)."""

from sort_sherr.models import Company, JobDraft
from sort_sherr.storage import db
from sort_sherr.tracker import lifecycle


def test_copy_database_keeps_ids_links_and_is_rerunnable(outreach_db, tmp_path):
    src = outreach_db["conn"]
    db.save_jobs(src, outreach_db["company"], 1, [JobDraft(title="ML Intern", is_internship=True, remote=None)])
    db.put_embeddings(src, [("h1", b"\x00\x01\x02")], "m")
    oid, _ = lifecycle.log_sent(src, outreach_db["drafts"][0], at="2026-11-02")
    fu = db.save_draft(src, {"match_id": None, "candidate_id": outreach_db["cand"], "company_id": outreach_db["company"],
                             "variant": "A", "style": "follow-up", "subject": "Re: x", "body": "b", "facts_used": [],
                             "student_items_used": [], "check_status": "ok", "check_notes": [], "lint_flags": [],
                             "outreach_id": oid, "followup_number": 1})

    dst = db.connect(tmp_path / "copy.db")
    counts = db.copy_database(src, dst, progress=lambda _: None)
    assert counts["companies"] == 1 and counts["outreach_events"] == 2
    assert db.copy_database(src, dst, progress=lambda _: None) == counts  # again: nothing breaks, nothing doubles
    assert dst.execute("SELECT count(*) FROM outreach_events").fetchone()[0] == 2

    o = db.get_outreach(dst, oid)  # same ids, links intact (incl. the drafts <-> outreach cycle)
    assert (o["company_name"], o["contact_value"], o["status"]) == ("Acme Labs", "ravi@acme.dev", "sent")
    assert db.get_draft(dst, fu)["outreach_id"] == oid
    assert db.get_embeddings(dst, ["h1"], "m") == {"h1": b"\x00\x01\x02"}
    job = db.company_jobs(dst, outreach_db["company"])[0]
    assert job["is_internship"] == 1 and job["remote"] is None  # tri-state survives
    new = db.upsert_company(dst, Company(name="Next Co", domain="next.co"))
    assert new > outreach_db["company"]  # new rows get fresh ids after the copied ones


def test_postgres_sql_translation():
    assert db._pg_sql("SELECT * FROM t WHERE a = ? AND b LIKE '%x%'", (1,)) == \
        "SELECT * FROM t WHERE a = %s AND b LIKE '%%x%%'"
    assert db._pg_sql("SELECT '%' FROM t", ()) == "SELECT '%' FROM t"  # no parameters: left alone
    assert db._pg_params([True, False, None, 3, "x"]) == [1, 0, None, 3, "x"]
    schema = db.pg_schema("id INTEGER PRIMARY KEY,\n company_id INTEGER PRIMARY KEY, v BLOB, s REAL")
    assert "id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY" in schema
    assert "company_id INTEGER PRIMARY KEY" in schema and "BYTEA" in schema and "DOUBLE PRECISION" in schema
    row = db.Row({"a": 0, "b": 1}, (5, "x"))
    assert row[0] == 5 and row["b"] == "x" and dict(row) == {"a": 5, "b": "x"} and tuple(row) == (5, "x")
